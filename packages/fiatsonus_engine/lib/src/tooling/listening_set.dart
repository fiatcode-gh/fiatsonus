import 'dart:math' as math;

import '../soundscapes/registry.dart';
import 'offline_render.dart';

/// One file of a listening set: its name, what it plays, and its render job.
final class ListeningItem {
  const ListeningItem(this.fileName, this.description, this.job);

  /// `NN-<name>.wav`, `NN` the two-digit position from `01`.
  final String fileName;
  final String description;
  final RenderJob job;
}

/// The sign-off questions per soundscape: the design doc's Acceptance list,
/// word for word, each with the files to play for it.
const Map<String, List<(String, String)>> _signOff = {
  'waterfall': [
    (
      'At Distance 0, it does not sound like TV static or a fan.',
      '08-distance-0.wav',
    ),
    (
      'At Distance 1, it sounds like a waterfall heard across a valley.',
      '09-distance-1.wav',
    ),
    (
      'Changing Height sounds like a bigger fall, not just louder bass.',
      '02-height-0.wav, 03-height-1.wav, 10-sweep-height.wav',
    ),
  ],
};

/// The listening set of [scapeId], built from its param list: defaults
/// (60 s), each param at 0 and at 1 (30 s each), one 0 → 1 → 0 sweep per
/// param (68 s), and a long defaults file of [longSeconds] (0 leaves it out).
/// Throws [ArgumentError] for an unknown soundscape, or a [longSeconds] that
/// is NaN or not 0 and below 6.
List<ListeningItem> listeningSet(
  String scapeId, {
  int sampleRate = 48000,
  int seed = 1,
  double longSeconds = 600,
}) {
  final scape = createSoundscape(scapeId);
  if (scape == null) {
    throw ArgumentError.value(scapeId, 'scapeId', 'unknown soundscape');
  }
  if (longSeconds.isNaN || (longSeconds != 0 && longSeconds < 6)) {
    throw ArgumentError.value(
      longSeconds,
      'longSeconds',
      'must be 0 or at least 6',
    );
  }
  final items = <ListeningItem>[];
  void add(
    String name,
    String description,
    double seconds, {
    Map<String, double> params = const {},
    String? sweepParam,
  }) {
    final nn = (items.length + 1).toString().padLeft(2, '0');
    items.add(
      ListeningItem(
        '$nn-$name.wav',
        description,
        RenderJob(
          scapeId: scapeId,
          sampleRate: sampleRate,
          seed: seed,
          seconds: seconds,
          params: params,
          sweepParam: sweepParam,
        ),
      ),
    );
  }

  add('defaults', 'defaults', 60);
  for (final p in scape.params) {
    add('${p.id}-0', '${p.id} = 0', 30, params: {p.id: 0.0});
    add('${p.id}-1', '${p.id} = 1', 30, params: {p.id: 1.0});
  }
  for (final p in scape.params) {
    add(
      'sweep-${p.id}',
      '${p.id} 0 -> 1 -> 0, about 30 s each way',
      68,
      sweepParam: p.id,
    );
  }
  if (longSeconds != 0) {
    add('defaults-long', 'defaults, long listen', longSeconds);
  }
  return items;
}

/// The `README.txt` of a rendered listening set: one line per file with
/// its loudness and peak, how to listen, and the sign-off questions. Throws
/// [ArgumentError] for an unknown soundscape, empty lists, or lists of
/// different lengths.
String listeningReadme(
  String scapeId,
  List<ListeningItem> items,
  List<RenderSummary> summaries,
) {
  if (items.isEmpty || items.length != summaries.length) {
    throw ArgumentError(
      'need one summary per item, got ${items.length} items and '
      '${summaries.length} summaries',
    );
  }
  final scape = createSoundscape(scapeId);
  if (scape == null) {
    throw ArgumentError.value(scapeId, 'scapeId', 'unknown soundscape');
  }
  final job = items.first.job;
  final defaults = [for (final p in scape.params) '${p.id} ${p.defaultValue}']
      .join(', ');

  final names = [for (final i in items) i.fileName];
  final seconds = [for (final i in items) '${i.job.seconds.toInt()} s'];
  final descriptions = [for (final i in items) i.description];
  final lufs = [for (final s in summaries) '${s.lufs.toStringAsFixed(1)} LUFS'];
  final peaks = [
    for (final s in summaries)
      'peak ${(20 * math.log(s.peak / 32768) / math.ln10).toStringAsFixed(1)} '
          'dBFS',
  ];
  int width(List<String> column) =>
      column.fold(0, (w, c) => math.max(w, c.length));
  final nameW = width(names);
  final secondsW = width(seconds);
  final descriptionW = width(descriptions);
  final lufsW = width(lufs);

  final out = StringBuffer()
    ..writeln('fiatsonus listening set: $scapeId')
    ..writeln(
      'Seed ${job.seed}, ${job.sampleRate} Hz, 16-bit stereo. '
      'Generated by tool/listening_set.dart. Every sound is made by code.',
    )
    ..writeln()
    ..writeln('Files (params not named stay at their defaults: $defaults)');
  for (var i = 0; i < items.length; i++) {
    out.writeln(
      '  ${names[i].padRight(nameW)}  ${seconds[i].padLeft(secondsW)}  '
      '${descriptions[i].padRight(descriptionW)}  '
      '${lufs[i].padLeft(lufsW)}  ${peaks[i]}',
    );
  }
  out
    ..writeln()
    ..writeln('How to listen')
    ..writeln('  - With headphones, then on a phone speaker.')
    ..writeln('  - At low volume: bad textures stand out more there.')
    ..writeln(
      '  - Play the long file without watching the screen. '
      'Note anything that repeats or sticks out.',
    )
    ..writeln()
    ..writeln('Sign-off: $scapeId (answer yes or no)');
  for (final (question, files) in _signOff[scapeId] ?? const []) {
    out.writeln('  [ ] $question  $files');
  }
  out
    ..writeln()
    ..writeln('Also note')
    ..writeln('  [ ] No click or jump in any sweep file.')
    ..writeln('  [ ] No audible repeat in the long file.');
  return out.toString();
}
